import {readFile, writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const branch=path.join(root,'biographies','webb-branch','people');
const people=['james_wilford','jonathan_henry','edward_milo_jr','edward_milo_sr','james_webb_jr'];
const audioFiles={
  james_wilford:'James_wilford_webb.mp3',
  jonathan_henry:'Jonathan_henry_webb.mp3',
  edward_milo_jr:'Edward_milo_webb_jr.mp3',
  edward_milo_sr:'Edward_milo_webb_sr.mp3',
  james_webb_jr:'James_webb_jr.mp3'
};
const flagKeys={
  james_wilford:'arizona-1917',
  jonathan_henry:'arizona-1917',
  edward_milo_jr:'united-states-period',
  edward_milo_sr:'united-states-period',
  james_webb_jr:'united-states-13-star'
};

const runtime={};
for(const personId of people){
  const dir=path.join(branch,personId);
  const [manifest,sceneManifest,narration]=await Promise.all([
    readFile(path.join(dir,'biography-manifest.json'),'utf8').then(JSON.parse),
    readFile(path.join(dir,'scene-manifest.json'),'utf8').then(JSON.parse),
    readFile(path.join(dir,'narration-approved.txt'),'utf8').then(value=>value.trim())
  ]);
  const scenes=sceneManifest.scenes.filter(scene=>scene.asset).map(scene=>({
    src:path.posix.join('biographies/webb-branch/people',personId,scene.asset),
    title:scene.title,
    caption:scene.assetBrief,
    source:`Approved Webb branch visual • ${scene.visualType}`,
    triggerParagraph:scene.paragraph,
    locator:scene.place||'Webb family context',
    flagKey:personId==='james_webb_jr'&&scene.id==='jwj-06-boundary'?'england-st-george':flagKeys[personId],
    visualType:scene.visualType
  }));
  runtime[personId]={
    audio:`approved-audio/fable/${audioFiles[personId]}`,
    narrator:'Fable',
    storyReady:true,
    transcript:narration,
    contract:'approved-webb-branch-production',
    visualStatus:sceneManifest.status,
    audioCandidates:[],
    scenes
  };
}

const banner='/* Generated by scripts/build-webb-runtime.mjs from approved Webb artifacts. */';
const output=`${banner}\nObject.assign(TOUR_MEDIA, ${JSON.stringify(runtime,null,2)});\n`;
await writeFile(path.join(root,'biographies','webb-branch','webb-story-modules.js'),output);
