import test from 'node:test';
import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFileSync} from 'node:fs';
const root=new URL('../',import.meta.url);
const html=readFileSync(new URL('atlas-v3.9.62.html',root),'utf8');
const src=readFileSync(new URL('jonathan-webb-local-history-sawmill-a064.js',root),'utf8');
test('A064 adds only institutional source with proper person and image rights boundaries',()=>{
 const DATA={nodes:[{id:'jonathan_henry',biography:'APPROVED STORY UNCHANGED',historicalNotes:[],evidence:[{kind:'photo',title:'Old family portrait',full:'old.jpg'}]}],edges:[{a:'james_wilford',b:'jonathan_henry',confidence:'confirmed'}]};
 const TOUR_MEDIA={jonathan_henry:{transcript:'FROZEN',audio:'old.mp3',scenes:[{src:'original-story.jpg'}]}};
 const GUIDE_PROFILES={jonathan_henry:{life:'APPROVED'}};
 const c=vm.createContext({DATA,TOUR_MEDIA,GUIDE_PROFILES});
 const graph=JSON.stringify(DATA.edges),tour=JSON.stringify(TOUR_MEDIA),guide=JSON.stringify(GUIDE_PROFILES);
 vm.runInContext(src,c,{timeout:3000});
 const p=DATA.nodes[0],e=p.evidence.find(x=>x.a064NewHistoricalSource);
 assert.ok(e);
 assert.match(e.sourcePage,/navajocountyhistory.org/);
 assert.match(e.documentUrl,/webb-sawmill-crew\.jpg/);
 assert.match(e.summary,/Jay Webb/);
 assert.equal(e.photoOfJonathanHimselfProven,false);
 assert.equal(p.sourceAudit.sawmillPhotoViewedInWeb,true);
 assert.equal(p.sourceAudit.sawmillPhotoOriginalMasterDownloaded,false);
 assert.equal(p.sourceAudit.sawmillPhotoCopyrightPermissionVerified,false);
 assert.equal(p.sourceAudit.oralHistoryAudioListened,false);
 assert.equal(p.sourceAudit.newImageBytesDownloaded,0);
 assert.equal(p.sourceAudit.fullyCertified,false);
 assert.match(p.historicalNotes[0].paragraphs[3],/Inez Prather/);
 assert.equal(p.biography,'APPROVED STORY UNCHANGED');
 assert.equal(JSON.stringify(DATA.edges),graph);
 assert.equal(JSON.stringify(TOUR_MEDIA),tour);
 assert.equal(JSON.stringify(GUIDE_PROFILES),guide);
 vm.runInContext(src,c,{timeout:3000});
 assert.equal(p.historicalNotes.length,1);
 assert.equal(p.evidence.filter(x=>x.a064NewHistoricalSource).length,1);
});
test('A064 script after A063 and only one loaded',()=>{
 const a='jay-1946-caption-source-hygiene-a063.js?v=20261112-a063',b='jonathan-webb-local-history-sawmill-a064.js?v=20261112-a064';
 assert.equal(html.split(b).length-1,1);
 assert.ok(html.indexOf(b)>html.indexOf(a));
});
