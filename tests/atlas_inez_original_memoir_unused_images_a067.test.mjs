import test from 'node:test';
import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFileSync} from 'node:fs';
const root=new URL('../',import.meta.url);
const html=readFileSync(new URL('atlas-v3.9.62.html',root),'utf8');
const src=readFileSync(new URL('inez-memoir-unused-images-caption-preflight-a067.js',root),'utf8');
test('A067 reuses the one genuinely unassigned Inez memoir image while preserving parents portraits and family graph',()=>{
 const DATA={nodes:[{id:'inez_karen',biography:'APPROVED Inez memoir',evidence:[{kind:'photo',title:'Inez 1963 graduation',full:'assets/inez-life-story/image6.jpeg'}],historicalNotes:[]},{id:'grace_hill',evidence:[{kind:'photo',full:'assets/inez-life-story/image2.jpeg'}]},{id:'thomas_prather',evidence:[{kind:'photo',full:'assets/inez-life-story/image1.jpeg'}]}],edges:[{a:'inez_karen',b:'grace_hill',confidence:'strong'},{a:'inez_karen',b:'thomas_prather',confidence:'strong'}]};
 const TOUR_MEDIA={inez_karen:{transcript:'FROZEN',audio:'original.mp3',scenes:[{src:'original.jpg'}]}};
 const GUIDE_PROFILES={inez_karen:{life:'APPROVED Inez memoir'}};
 const c=vm.createContext({DATA,TOUR_MEDIA,GUIDE_PROFILES});
 const b=JSON.stringify(DATA.edges),t=JSON.stringify(TOUR_MEDIA),g=JSON.stringify(GUIDE_PROFILES),parents=JSON.stringify(DATA.nodes.slice(1));
 vm.runInContext(src,c,{timeout:3000});
 const i=DATA.nodes[0],portrait=i.evidence.find(e=>e.a067RecoveredFromUnreferencedExistingImage===true);
 assert.ok(portrait);
 assert.equal(portrait.full,'assets/inez-life-story/image44.jpeg');
 assert.equal(portrait.date,'May 2023');
 assert.match(portrait.provenance,/page 115 of 118/);
 assert.match(portrait.transcription,/Passport Picture, May, 2023/);
 assert.equal(portrait.archivalImageAlreadyPresent,true);
 assert.equal(portrait.officialPassportOriginalInspected,false);
 assert.equal(portrait.iPhoneFullScreenVerified,false);
 assert.equal(i.evidence.length,2);
 assert.equal(i.historicalNotes.length,1);
 assert.equal(i.sourceAudit.folderFiles,42);
 assert.equal(i.sourceAudit.memoirModulePhotoCards,39);
 assert.equal(i.sourceAudit.projectedPhotosAfterA067,45);
 assert.equal(i.sourceAudit.all118MemoirPagesSourceImageAudited,false);
 assert.equal(i.sourceAudit.newAssetBytes,0);
 assert.equal(i.biography,'APPROVED Inez memoir');
 assert.equal(JSON.stringify(DATA.edges),b);
 assert.equal(JSON.stringify(TOUR_MEDIA),t);
 assert.equal(JSON.stringify(GUIDE_PROFILES),g);
 assert.equal(JSON.stringify(DATA.nodes.slice(1)),parents);
 vm.runInContext(src,c,{timeout:3000});
 assert.equal(i.evidence.length,2);
 assert.equal(i.historicalNotes.length,1);
});
